CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    action VARCHAR(40) NOT NULL CHECK (action IN ('EVENT_CREATE', 'EVENT_UPDATE', 'EVENT_OPEN', 'EVENT_CLOSE', 'EVENT_DELETE', 'PARTICIPANT_REMOVE')),
    target_type VARCHAR(20) NOT NULL CHECK (target_type = 'EVENT'),
    target_id BIGINT NOT NULL,
    reason TEXT,
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_logs_target ON audit_logs (target_type, target_id, created_at DESC, id DESC);
