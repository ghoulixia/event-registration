CREATE TABLE waitlist_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMP,

    CONSTRAINT fk_waitlist_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_waitlist_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT chk_waitlist_status CHECK (status IN ('WAITING', 'LEFT'))
);

CREATE UNIQUE INDEX uk_waitlist_active_user_event
    ON waitlist_entries (user_id, event_id)
    WHERE status = 'WAITING';

CREATE INDEX idx_waitlist_event_fifo
    ON waitlist_entries (event_id, joined_at, id)
    WHERE status = 'WAITING';
